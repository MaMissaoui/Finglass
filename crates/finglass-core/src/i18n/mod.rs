/// A supported UI language.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]
pub enum Language {
    /// English.
    En,
    /// German.
    De,
    /// French.
    Fr,
}

impl Language {
    /// All supported languages.
    pub const ALL: &[Language] = &[Language::En, Language::De, Language::Fr];

    /// The ISO code stored in the settings.
    #[must_use]
    pub fn code(self) -> &'static str {
        match self {
            Language::En => "en",
            Language::De => "de",
            Language::Fr => "fr",
        }
    }

    /// The language's own name, as shown in the language picker.
    #[must_use]
    pub fn native_name(self) -> &'static str {
        match self {
            Language::En => "English",
            Language::De => "Deutsch",
            Language::Fr => "Français",
        }
    }

    /// Parses a stored ISO code, ignoring case.
    #[must_use]
    pub fn from_code(code: &str) -> Option<Language> {
        if code.eq_ignore_ascii_case("en") {
            Some(Language::En)
        } else if code.eq_ignore_ascii_case("de") {
            Some(Language::De)
        } else if code.eq_ignore_ascii_case("fr") {
            Some(Language::Fr)
        } else {
            None
        }
    }

    /// Whether `count` takes the singular: French also uses it for zero, the other languages only for one.
    #[must_use]
    pub fn is_singular(self, count: i64) -> bool {
        match self {
            Language::Fr => count == 0 || count == 1,
            Language::En | Language::De => count == 1,
        }
    }
}

