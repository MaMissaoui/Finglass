package i18n

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
)

const (
	frontendDirMode  os.FileMode = 0o755
	frontendFileMode os.FileMode = 0o644
)

// WriteFrontend writes keys.ts and the three JSON tables into dir.
func WriteFrontend(dir string) error {
	if err := os.MkdirAll(dir, frontendDirMode); err != nil {
		return fmt.Errorf("create %s: %w", dir, err)
	}
	if err := writeFile(filepath.Join(dir, "keys.ts"), frontendKeys()); err != nil {
		return err
	}
	for _, lang := range Languages {
		data, err := frontendTable(lang)
		if err != nil {
			return err
		}
		if err := writeFile(filepath.Join(dir, lang.Code()+".json"), data); err != nil {
			return err
		}
	}
	return nil
}

func frontendKeys() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/core/i18n; DO NOT EDIT.\n\n")
	b.WriteString("export const keys = [\n")
	for _, key := range All() {
		fmt.Fprintf(&b, "  '%s',\n", key.String())
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type Key = (typeof keys)[number];\n")
	return b.Bytes()
}

func frontendTable(lang Language) ([]byte, error) {
	keys := All()
	var b bytes.Buffer
	b.WriteString("{\n")
	for i, key := range keys {
		name, err := encodeJSON(key.String())
		if err != nil {
			return nil, err
		}
		value, err := encodeJSON(Text(lang, key))
		if err != nil {
			return nil, err
		}
		b.WriteString("  ")
		b.Write(name)
		b.WriteString(": ")
		b.Write(value)
		if i < len(keys)-1 {
			b.WriteByte(',')
		}
		b.WriteByte('\n')
	}
	b.WriteString("}\n")
	return b.Bytes(), nil
}

func encodeJSON(value any) ([]byte, error) {
	var b bytes.Buffer
	encoder := json.NewEncoder(&b)
	encoder.SetEscapeHTML(false)
	if err := encoder.Encode(value); err != nil {
		return nil, fmt.Errorf("encode JSON: %w", err)
	}
	return bytes.TrimSuffix(b.Bytes(), []byte{'\n'}), nil
}

func writeFile(path string, data []byte) error {
	if err := os.WriteFile(path, data, frontendFileMode); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}
